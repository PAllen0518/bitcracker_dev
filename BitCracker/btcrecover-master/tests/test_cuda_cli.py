def test_cli_complete_and_resume_have_exact_counts(tmp_path):
    checkpoint = tmp_path / "synthetic.bin"
    result = run_app(
        tmp_path,
        "+ab cd\n+ef\n",
        "--batch-size",
        "3",
        "--timings",
        "--autosave",
        str(checkpoint),
    )
    assert result.returncode == 0, result.stderr
    assert timing_values(result.stdout)["count"] == 4
    assert "Not found" in result.stdout
    data = checkpoint.read_bytes()
    # Existing layout: two 512-byte paths, three counters, two offsets.
    combo, total, checked = struct.unpack_from("<QQQ", data, 1024)
    assert combo == total == 2
    assert checked == 4
    resumed = subprocess.run(
        [
            str(APP),
            "--restore",
            str(checkpoint),
            "--batch-size",
            "3",
            "--timings",
        ],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert resumed.returncode == 0, resumed.stderr
    assert timing_values(resumed.stdout)["count"] == 0
    assert "0 passwords" in resumed.stdout


def test_cli_mid_typo_resume_preserves_remaining_count(tmp_path):
    checkpoint = tmp_path / "synthetic.bin"
    options = [
        "--batch-size",
        "3",
        "--typos",
        "1",
        "--typos-repeat",
        "--typos-delete",
        "--timings",
    ]
    result = run_app(
        tmp_path,
        "+ab\n",
        *options,
        "--autosave",
        str(checkpoint),
    )
    assert result.returncode == 0, result.stderr
    assert timing_values(result.stdout)["count"] == 5
    data = bytearray(checkpoint.read_bytes())
    struct.pack_into("<Q", data, 1024, 0)
    struct.pack_into("<Q", data, 1040, 2)
    struct.pack_into("<QQ", data, 1048, 0, 2)
    checkpoint.write_bytes(data)
    result = subprocess.run(
        [str(APP), "--restore", str(checkpoint), *options],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert result.returncode == 0, result.stderr
    assert timing_values(result.stdout)["count"] == 3
